// Seed generator calculating dynamic emissions for each mine
export function initializeMines(): MineRecord[] {
  return rawMinesSeed.map(m => {
    const emissions = calculationEngine.calculateEmissions(
      m.operational,
      m.mineType,
      m.gassinessDegree || 1,
      (m.operational.renewableEnergyKWh * 0.716) / 1000
    );

    // Mock 6-month historical log for charts
    const baseCoal = m.operational.coalExtractedTonnes;
    const baseEm = emissions.totalGrossEmissions;
    const history = [
      { period: 'Sep 2025', productionTonnes: Math.round(baseCoal * 0.94), emissionsTco2e: Math.round(baseEm * 0.96), intensity: round((baseEm * 0.96) / (baseCoal * 0.94), 4), status: 'verified' as const },
      { period: 'Oct 2025', productionTonnes: Math.round(baseCoal * 0.97), emissionsTco2e: Math.round(baseEm * 0.98), intensity: round((baseEm * 0.98) / (baseCoal * 0.97), 4), status: 'verified' as const },
      { period: 'Nov 2025', productionTonnes: Math.round(baseCoal * 1.02), emissionsTco2e: Math.round(baseEm * 1.01), intensity: round((baseEm * 1.01) / (baseCoal * 1.02), 4), status: 'verified' as const },
      { period: 'Dec 2025', productionTonnes: Math.round(baseCoal * 1.05), emissionsTco2e: Math.round(baseEm * 1.04), intensity: round((baseEm * 1.04) / (baseCoal * 1.05), 4), status: 'verified' as const },
      { period: 'Jan 2026', productionTonnes: Math.round(baseCoal * 1.01), emissionsTco2e: Math.round(baseEm * 1.00), intensity: round((baseEm * 1.00) / (baseCoal * 1.01), 4), status: 'verified' as const },
      { period: 'Feb 2026', productionTonnes: baseCoal, emissionsTco2e: Math.round(baseEm), intensity: emissions.carbonIntensityTco2ePerTonne, status: m.anomalies.length > 0 ? ('flagged' as const) : ('verified' as const) },
    ];

    return {
      ...m,
      emissions,
      reportingHistory: history,
    };
  });
}

function round(val: number, decimals: number): number {
  const factor = Math.pow(10, decimals);
  return Math.round(val * factor) / factor;
}
